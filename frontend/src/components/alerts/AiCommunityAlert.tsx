"use client";

import { Info, Languages } from "lucide-react";
import { useState } from "react";
import { Badge } from "@/components/ui/badge";
import { Card, CardContent, CardHeader } from "@/components/ui/card";
import { HARDCODED_TODAY } from "@/data/hardcodedDisplay";
import { cn } from "@/lib/utils";
import type { FloodStatus } from "@/types/floodshield";

interface AiCommunityAlertProps {
  status: FloodStatus;
}

export function AiCommunityAlert({ status }: AiCommunityAlertProps) {
  const [lang, setLang] = useState<"en" | "ur">("en");
  const englishAlert = HARDCODED_TODAY.english_alert;
  const urduAlert = HARDCODED_TODAY.urdu_alert;

  return (
    <Card>
      <CardHeader>
        <div className="flex flex-col gap-3 sm:flex-row sm:items-start sm:justify-between">
          <div>
            <div className="flex flex-wrap items-center gap-2">
              <h3 className="text-lg font-semibold text-slate-900 dark:text-slate-50">
                Community Alert
              </h3>
              <Badge variant="soft">
                <Languages className="h-3.5 w-3.5" />
                Generated by Qwen AI
              </Badge>
            </div>
            <p className="mt-2 text-sm text-slate-500 dark:text-slate-400">
              Plain-language flood intelligence for communities in English and
              Urdu — based on today&apos;s {HARDCODED_TODAY.final_alert} risk at{" "}
              {status.station}.
            </p>
          </div>

          <div className="inline-flex rounded-xl border border-slate-200 bg-slate-50 p-1 dark:border-slate-700 dark:bg-slate-800">
            <button
              type="button"
              onClick={() => setLang("en")}
              className={cn(
                "rounded-lg px-3 py-1.5 text-sm font-medium transition-colors",
                lang === "en"
                  ? "bg-white text-slate-900 shadow-sm dark:bg-slate-900 dark:text-slate-50"
                  : "text-slate-500 hover:text-slate-800 dark:text-slate-400 dark:hover:text-slate-200",
              )}
            >
              English
            </button>
            <button
              type="button"
              onClick={() => setLang("ur")}
              className={cn(
                "rounded-lg px-3 py-1.5 text-sm font-medium transition-colors",
                lang === "ur"
                  ? "bg-white text-slate-900 shadow-sm dark:bg-slate-900 dark:text-slate-50"
                  : "text-slate-500 hover:text-slate-800 dark:text-slate-400 dark:hover:text-slate-200",
              )}
            >
              اردو
            </button>
          </div>
        </div>
      </CardHeader>

      <CardContent className="space-y-4">
        {lang === "en" ? (
          <div className="rounded-2xl border border-slate-200 bg-slate-50 p-5 dark:border-slate-700 dark:bg-slate-800/60 sm:p-6">
            <p className="text-[15px] leading-7 text-slate-700 dark:text-slate-200">
              {englishAlert}
            </p>
          </div>
        ) : (
          <div
            dir="rtl"
            lang="ur"
            className="rounded-2xl border border-slate-200 bg-slate-50 p-5 text-right dark:border-slate-700 dark:bg-slate-800/60 sm:p-6"
          >
            <p className="font-[family-name:var(--font-noto-urdu)] text-[18px] leading-9 text-slate-800 dark:text-slate-100">
              {urduAlert}
            </p>
          </div>
        )}

        <div className="flex gap-3 rounded-xl border border-sky-200 bg-sky-50 px-4 py-3 text-sm text-sky-950 dark:border-sky-800 dark:bg-sky-950/40 dark:text-sky-100">
          <Info className="mt-0.5 h-4 w-4 shrink-0" />
          <p>
            Always follow instructions issued by PMD, FFD, PDMA and local
            authorities.
          </p>
        </div>
      </CardContent>
    </Card>
  );
}
